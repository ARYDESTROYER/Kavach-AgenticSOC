/**
 * Stable, order-insensitive structural equality for two JSON-able values.
 *
 * Shared by the Settings per-section dirty map (`soc/pages/settings-dirty.ts`, which
 * re-exports it) and the general draft hook (`soc/hooks/useDirtyDraft.ts`). It lives in
 * its own dependency-free module because the shell's unsaved-changes guard imports the
 * hook eagerly: importing it from `settings-dirty` would pull the whole Settings section
 * metadata into the first-paint entry chunk.
 */
export function deepEqual(a: unknown, b: unknown): boolean {
  if (a === b) return true;
  if (a === null || b === null) return a === b;
  if (typeof a !== typeof b) return false;
  if (typeof a !== 'object') return false;

  const aArr = Array.isArray(a);
  const bArr = Array.isArray(b);
  if (aArr !== bArr) return false;
  if (aArr && bArr) {
    if (a.length !== b.length) return false;
    for (let i = 0; i < a.length; i += 1) {
      if (!deepEqual(a[i], b[i])) return false;
    }
    return true;
  }

  const ao = a as Record<string, unknown>;
  const bo = b as Record<string, unknown>;
  const aKeys = Object.keys(ao);
  const bKeys = Object.keys(bo);
  if (aKeys.length !== bKeys.length) return false;
  for (const k of aKeys) {
    if (!Object.prototype.hasOwnProperty.call(bo, k)) return false;
    if (!deepEqual(ao[k], bo[k])) return false;
  }
  return true;
}
